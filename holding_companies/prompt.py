from __future__ import annotations

import json

from holding_companies.policy import STATUS_REASONS


def build_extraction_prompt(*, email_text: str, attachment_name: str, attachment_text: str) -> str:
    reasons = sorted(STATUS_REASONS)
    return f"""
Извлеки сведения о закрытом тендере холдинга из текста письма и одного вложения.
Верни только JSON, строго по схеме.

Правила по полям:
- proposalStartDate — дата и время начала подачи предложения, если они прямо указаны;
- proposalEndDate — дата и время окончания/срока подачи предложения, не дата действия цены;
- holdingCompany — наименование холдинга/заказчика из письма или вложения;
- supplyConditions — кратко: Incoterms, место/адрес и существенные ограничения поставки;
- sourceUrl — ссылка на страницу закупки/CRM холдинга с подробной информацией, а не ссылка на инструкцию;
- paymentDelay — только срок отсрочки оплаты. Если указан лишь код условия оплаты (например KOIK), сохрани его как есть и не выдумывай число дней;
- deliveryEndDate — конечная дата поставки, только если она прямо указана; не путай со сроком подачи предложения;
- lotDivisible — false только при прямом требовании поставить весь лот целиком/неделимости, true при прямом разрешении частичной или попозиционной поставки, иначе null;
- deliveryNote — краткая полезная для сотрудника информация о доставке, маркировке, частичных поставках, аналогах и упаковке;
- products — только реально закупаемые товары из вложения. Не включай адреса, услуги площадки, реквизиты, заголовки и инструкции.

Для каждой позиции products сохрани полное наименование, количество, единицу, марку/артикул и характеристики, только если они относятся к товару.
Не создавай товары из текста письма, если перечень товаров находится во вложении.
Не выдумывай характеристики, количество, сроки или URL.

Разрешённые причины отказа: {json.dumps(reasons, ensure_ascii=False)}.
Если подтверждена ровно одна главная причина из справочника, поставь tenderStatus="Отказано",
tenderStatusReason равной точному тексту причины и statusReasonEvidence с короткой дословной
цитатой. Иначе tenderStatus="Согласовано", tenderStatusReason="".

Строгие ограничения против ложных отказов:
- «Оборудование 35 кВ и выше» — только если сама закупаемая товарная позиция является
  высоковольтным электротехническим оборудованием с напряжением >=35 кВ. Изолятор, арматура,
  крепёж, зажим, комплектующая, расходный материал, а также напряжение ПС/ЛЭП/объекта установки
  не являются основанием.
- «Частотный привод 6–10 кВ» — только если закупается именно частотный привод такого класса.
- «Ремкомплект / ЗИП / продукция по чертежу» — только если закупается ЗИП, ремкомплект,
  запасная часть либо требуется изготовление по чертежу. Не срабатывает на ОКПД2,
  слово «комплектующие» или шаблон договора.
- «Поставка с работами» — только при обязательных монтажных, пусконаладочных, установочных
  работах или вводе в эксплуатацию именно по предмету закупки.
- «Консигнация / хранение» — только при прямой обязанности хранить товар у покупателя
  за счёт поставщика. Обычная доставка и приёмка не являются консигнацией.
- «Поставка в удалённые территории» — только при явном требовании доставки в удалённую /
  труднодоступную территорию, зимником, авиацией, на месторождение и подобном. Обычный
  адрес филиала сам по себе не основание.

ТЕКСТ ПИСЬМА:
{email_text}

ИМЯ ВЛОЖЕНИЯ: {attachment_name or "не указано"}
ТЕКСТ ВЛОЖЕНИЯ:
{attachment_text}
""".strip()
