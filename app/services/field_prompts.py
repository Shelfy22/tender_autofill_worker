def active_extraction_rules() -> str:
    blocks = [EXTRACTION_BASE]
    if is_tender_field_enabled("nationalRegime"):
        blocks.append(EXTRACTION_NATIONAL)
    # Detailed instructions per delivery field are shared with document analysis.
    blocks.extend(document_rule(name) for name in DOCUMENT_FIELDS
                  if name != "nationalRegime" and is_tender_field_enabled(name))
    return "\n".join(blocks)


def document_rule(name: str) -> str:
    if name == "deliveryNote" and not is_tender_field_enabled("deliveryType"):
        return (
            "- deliveryNote — краткое фактическое примечание к поставке: разгрузка, "
            "заявки, график и особые условия. Не определяй тип отгрузки и не "
            "возвращай только единицу срока без фактического условия."
        )
    return DOCUMENT_FIELDS.get(name, "") if is_tender_field_enabled(name) else ""


def active_commercial_targets() -> list[str]:
    return [name for name in COMMERCIAL_FIELDS
            if any(is_tender_field_enabled(field) for field in name.split(", ")
                   if field != "deliveryNote")]


def active_commercial_rules() -> str:
    return "\n\n".join(COMMERCIAL_FIELDS[name] for name in active_commercial_targets())


def commercial_field_names() -> list[str]:
    return [name for group in active_commercial_targets() for name in group.split(", ")
            if is_tender_field_enabled(name)]


def active_consolidation_rules() -> str:
    blocks = []
    if is_tender_field_enabled("nationalRegime"):
        blocks.append(CONSOLIDATION_NATIONAL)
    if is_tender_field_enabled("paymentDelayDays"):
        blocks.append(COMMERCIAL_FIELDS["paymentDelayDays"])
    if is_tender_field_enabled("deliveryBatchDays"):
        blocks.append(DOCUMENT_FIELDS["deliveryBatchDays"])
    return "\n".join(blocks)
